// Every folder on the way to a published file, parents first.
export function publishedFolders(files: readonly string[] = PUBLISHED_FILES): string[] {
  const folders = new Set<string>();
  for (const file of files) {
    const parts = file.split("/").slice(0, -1);
    for (let depth = 1; depth <= parts.length; depth += 1) folders.add(parts.slice(0, depth).join("/"));
  }
  return [...folders].sort();
}

const HEADER = `# Generated by tests/support/write-assetsignore.ts from PUBLISHED_FILES in
# tests/support/published-files.ts. Do not edit it by hand: to publish a file,
# add it to that list and run the script.
#
# Wrangler uploads every file in this directory that is not ignored here,
# whether git tracks it or not. So everything is ignored, then each folder on
# the way to a published file is re-included (folders must come first), then
# each published file. _headers is deliberately not re-included: wrangler
# reads it without publishing it.
`;

// The exact content of .assetsignore for a list of files.
export function assetsIgnore(files: readonly string[] = PUBLISHED_FILES): string {
  const folders = publishedFolders(files).map((folder) => `!${folder}/`);
  const published = files.map((file) => `!/${file}`);
  return `${HEADER}*\n${folders.join("\n")}\n${published.join("\n")}\n`;
}
